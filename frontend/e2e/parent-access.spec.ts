import { expect, test } from '@playwright/test'

test('the welcome screen separates roles and the cabinet requires PIN after leaving', async ({
  page,
}) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Я ребёнок' })).toBeVisible()
  await page.getByRole('button', { name: 'Я родитель' }).click()
  await expect(page.getByRole('heading', { name: 'Родительский режим' })).toBeVisible()
  await page.getByLabel('Новый PIN', { exact: true }).fill('0639')
  await page.getByLabel('Повторите PIN').fill('0638')
  await page.getByRole('button', { name: 'Создать PIN и войти' }).click()
  await expect(page.getByText('PIN-коды должны совпадать.')).toBeVisible()
  await page.getByLabel('Повторите PIN').fill('0639')
  await page.getByRole('button', { name: 'Создать PIN и войти' }).click()
  await expect(page.getByRole('heading', { name: 'Копилка ребёнка' })).toBeVisible()
  await page.getByRole('button', { name: 'Закрыть и выйти в копилку' }).click()
  await expect(page.getByRole('heading', { name: 'Моя копилка' })).toBeVisible()
  await page.goto('/app/parent/feedback')
  await expect(page.getByRole('heading', { name: 'Родительский режим' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Сохранить отзыв' })).toHaveCount(0)
  expect((await page.request.get('/api/feedback/export')).status()).toBe(403)
  await page.getByLabel('PIN', { exact: true }).fill('1111')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByText('Неверный PIN. Попробуйте ещё раз.')).toBeVisible()
  await page.getByLabel('PIN', { exact: true }).fill('0639')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сохранить отзыв' })).toBeVisible()
  await page.goto('/')
  await page.getByRole('button', { name: 'Я ребёнок' }).click()
  await expect(page.getByRole('heading', { name: 'Мои три отсека' })).toBeVisible()
  expect((await (await page.request.get('/api/demo/parent')).json()).unlocked).toBe(false)
})
